import { Fragment, type ReactNode } from "react";
import { useQuery } from "@tanstack/react-query";
import { GuestAuthNotice } from "@/components/gate/SandboxBanner";
import { fetchExport } from "@/lib/api";
import { inlineTokens, markdownBlocks, parseNotebook, type InlineToken, type NotebookCell } from "@/lib/notebook";
import { cn } from "@/lib/utils";
import type { ExportFormat } from "@/types";

/**
 * Gate 4's notebook preview: the notebook FILE, fetched from the export route and drawn cell by cell the way Jupyter
 * draws an unexecuted notebook (review round 8, Bhargav: "I want user to see an exact preview").
 *
 * It reads the same bytes the download carries — the backend writes the notebook from the run plus the caller's
 * gate decisions — so it cannot say something the file does not. Markdown is parsed into tokens
 * (`lib/notebook.ts`) and drawn as React elements, never as HTML, so a cell cannot inject markup.
 *
 * A GUEST on the shared demo gets the sign-in notice instead: the export route is not on the guest surface
 * (`backend/app.py` `_DEMO_SCOPED_JOB_READS`), and this preview is that route's file.
 */
export function NotebookPreview({
  jobId,
  format,
  guestLocked,
}: {
  jobId: string;
  format: ExportFormat;
  guestLocked: boolean;
}) {
  const { data, error, isPending } = useQuery({
    queryKey: ["export-file", jobId, format],
    queryFn: async () => parseNotebook(await (await fetchExport(jobId, format)).text()),
    enabled: !guestLocked,
    retry: false,
  });

  if (guestLocked) {
    return (
      <p data-testid="notebook-preview" data-state="guest" className="text-sm text-on-raised-muted">
        <GuestAuthNotice action="previewing the notebook" />
      </p>
    );
  }
  if (isPending) {
    return (
      <p data-testid="notebook-preview" data-state="loading" className="text-sm text-on-raised-muted">
        Reading the notebook…
      </p>
    );
  }
  if (error || !data) {
    return (
      <p data-testid="notebook-preview" data-state="error" className="text-sm text-on-raised-muted">
        {error ? error.message : "This file did not read as a notebook."}
      </p>
    );
  }

  const language = data.language ? `${data.language[0]!.toUpperCase()}${data.language.slice(1)}` : "Code";
  return (
    <div
      data-testid="notebook-preview"
      data-state="ready"
      className="flex min-h-0 flex-1 flex-col gap-3 overflow-auto rounded-inner border border-rule-on-raised p-4"
    >
      {data.cells.map((cell, i) => (
        <NotebookCellView key={i} cell={cell} language={language} />
      ))}
    </div>
  );
}

/** One cell: a gutter (Jupyter's `In [ ]:` on a code cell, blank otherwise) beside its content. */
function NotebookCellView({ cell, language }: { cell: NotebookCell; language: string }) {
  return (
    <div data-testid="notebook-cell" data-kind={cell.kind} className="grid grid-cols-[4rem_minmax(0,1fr)] gap-2">
      <span aria-hidden className="pt-2 text-right font-mono text-xs text-on-raised-faint">
        {cell.kind === "code" ? "In [ ]:" : ""}
      </span>
      {cell.kind === "markdown" ? (
        <div className="flex flex-col gap-2 text-sm text-on-raised">
          {markdownBlocks(cell.source).map((b, i) => (
            <MarkdownBlockView key={i} block={b} />
          ))}
        </div>
      ) : (
        <pre
          aria-label={cell.kind === "code" ? `${language} code` : "Raw cell"}
          className={cn(
            "overflow-x-auto whitespace-pre rounded-inner p-3 font-mono text-xs leading-relaxed",
            cell.kind === "code" ? "border border-rule-on-raised bg-surface-inset text-on-inset" : "text-on-raised-muted",
          )}
        >
          {cell.source}
        </pre>
      )}
    </div>
  );
}

const HEADING_CLASS: Record<number, string> = {
  1: "text-lg font-semibold",
  2: "text-base font-semibold",
};

function MarkdownBlockView({ block }: { block: ReturnType<typeof markdownBlocks>[number] }) {
  if (block.kind === "heading") {
    const Tag = `h${Math.min(block.level, 6)}` as "h1" | "h2" | "h3" | "h4" | "h5" | "h6";
    return <Tag className={HEADING_CLASS[block.level] ?? "text-sm font-semibold"}>{inline(block.text)}</Tag>;
  }
  if (block.kind === "list") {
    const List = block.ordered ? "ol" : "ul";
    return (
      <List className={cn("flex flex-col gap-1 pl-5", block.ordered ? "list-decimal" : "list-disc")}>
        {block.items.map((item, i) => (
          <li key={i}>{inline(item)}</li>
        ))}
      </List>
    );
  }
  return <p className="leading-relaxed">{inline(block.text)}</p>;
}

/**
 * A block's inline emphasis and code as elements. Emphasis is read again inside itself, because the backend's own
 * header nests them (`_Generated by **ddharmon**._`): the italic run carries a bold one.
 */
function inline(text: string): ReactNode {
  return inlineTokens(text).map((t: InlineToken, i) => {
    if (t.kind === "code") {
      return (
        <code key={i} className="rounded-inner bg-surface-inset px-1 font-mono text-xs text-on-inset">
          {t.text}
        </code>
      );
    }
    if (t.kind === "strong") return <strong key={i}>{inline(t.text)}</strong>;
    if (t.kind === "em") return <em key={i}>{inline(t.text)}</em>;
    return <Fragment key={i}>{t.text}</Fragment>;
  });
}
